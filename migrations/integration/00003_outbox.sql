--
-- Транзакционный outbox: способ не потерять событие, когда запись в базу
-- прошла, а публикация в RabbitMQ — нет.
--
-- Идея одна: строка в outbox пишется ТОЙ ЖЕ транзакцией, что и сама
-- фиксация. Либо в базе есть и фиксация, и задание на публикацию, либо
-- нет ни того ни другого. Публикацией занимается отдельный воркер, который
-- читает эту таблицу. Отправить в брокер прямо из транзакции нельзя:
-- брокер не участвует в COMMIT, и на откате уже улетевшее сообщение
-- назад не вернёшь.
--
-- ВНИМАНИЕ: схема здесь намеренно минимальная и неполная. Её хватает,
-- чтобы записать событие, и НЕ хватает, чтобы построить надёжный воркер.
-- Чего именно не хватает — предмет отдельного тикета по воркеру.

-- +goose Up
-- +goose StatementBegin

create table if not status integration.outbox (
    -- Суррогатный ключ. bigserial, а не uuid: outbox читают пачками по
    -- возрастанию id, и монотонный int64 для этого удобнее и компактнее
    -- в индексе, чем случайный uuid.
    id              bigserial   primary key,

    -- На какой объект событие. Пара (тип, id) вместо внешнего ключа:
    -- в одну таблицу пишут события про разные сущности, и FK на каждую
    -- превратил бы её в узел связности всей схемы.
    aggregate_type  text        not null,
    aggregate_id    uuid        not null,

    -- Имя события в терминах предметной области: fixation.created,
    -- fixation.expired. Именно оно станет routing key в RabbitMQ.
    -- Не статус объекта: статус — это «сейчас», событие — это «случилось».
    event_type      text        not null,

    -- Тело сообщения. jsonb, а не json: он хранится разобранным, его можно
    -- индексировать и читать по ключу. Схему тела фиксируем не здесь,
    -- а в контракте события — база тут просто транспорт.
    payload         jsonb       not null,

    -- Когда событие поставлено в очередь. Нужен и для разбора инцидентов,
    -- и для сортировки: воркер обязан соблюдать порядок появления.
    created_at      timestamptz not null default now(),

    -- Когда воркер подтвердил публикацию. NULL = ещё не опубликовано.
    -- Отдельная колонка времени, а не булев флаг: по ней сразу видно,
    -- сколько событие пролежало, и это главный признак «воркер встал».
    published_at    timestamptz
);

comment on table integration.outbox is
    'Транзакционный outbox. Схема намеренно неполная: под надёжный воркер её надо дорабатывать.';

-- Рабочий индекс воркера: «дай следующие N неопубликованных по порядку».
-- Частичный (where published_at is null) — в индексе лежат только
-- невыполненные задания. Опубликованные строки, которых со временем
-- станут миллионы, в индекс не попадают вообще, и он остаётся маленьким
-- независимо от размера таблицы.
create index if not status outbox_unpublished_idx
    on integration.outbox (id)
    where published_at is null;

-- «Что мы вообще отправляли про эту фиксацию» — вопрос при расследовании
-- расхождений с amoCRM. Без этого индекса это seq scan по всей таблице.
create index if not status outbox_aggregate_idx
    on integration.outbox (aggregate_type, aggregate_id, created_at);

-- ── Dead letter queue ────────────────────────────────────────────────
--
-- Куда воркер откладывает то, что опубликовать не удалось и повторять
-- бессмысленно. Зачем отдельная таблица, а не колонка-флаг в outbox:
-- рабочий индекс outbox должен оставаться коротким. Одно навсегда
-- сломанное сообщение не должно попадаться воркеру на каждом цикле.
--
-- Разбирают DLQ руками: это очередь к человеку, а не к процессу.
create table if not status integration.outbox_dlq (
    -- Свой ключ. Исходный id сохраняем отдельным полем: связь с outbox
    -- нужна для расследования, но не как FK — строку в outbox могут
    -- удалить при чистке, а DLQ обязан её пережить.
    id              bigserial   primary key,
    outbox_id       bigint      not null,

    -- Полная копия события. Именно копия, а не ссылка: DLQ должна быть
    -- самодостаточной, иначе после чистки outbox в ней останутся
    -- идентификаторы без содержимого.
    aggregate_type  text        not null,
    aggregate_id    uuid        not null,
    event_type      text        not null,
    payload         jsonb       not null,

    -- Когда событие было создано изначально: по нему видно, насколько
    -- старое сообщение мы потеряли.
    created_at      timestamptz not null,

    -- Когда его сюда переложили.
    moved_at        timestamptz not null default now(),

    -- Текст последней ошибки как есть, без разбора на категории.
    -- Разбор — это уже решение о том, что повторять, а что нет;
    -- он живёт в коде воркера, не в схеме.
    last_error      text
);

comment on table integration.outbox_dlq is
    'Сообщения, которые воркер не смог опубликовать. Разбирается руками.';

-- «Что лежит в DLQ и с каких пор» — единственный регулярный запрос:
-- по нему строится алерт «в DLQ что-то есть».
create index if not status outbox_dlq_moved_at_idx
    on integration.outbox_dlq (moved_at desc);

-- «Найди в DLQ всё по этой фиксации» — при разборе конкретной жалобы.
create index if not status outbox_dlq_aggregate_idx
    on integration.outbox_dlq (aggregate_type, aggregate_id);

