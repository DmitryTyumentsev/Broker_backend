#!/bin/sh
# Один контейнер, два процесса: веб-сервер и консьюмер очереди.
#
# В проде это два разных деплоймента: у них разный профиль нагрузки и
# масштабируются они независимо (веб — по RPS, консьюмер — по глубине
# очереди). Здесь они вместе, потому что это стенд и лишний контейнер
# ничего не объясняет.
#
# set -e: любая ошибка на старте валит контейнер, а не оставляет его
# наполовину живым.
set -e

php /app/bin/consumer.php &
CONSUMER_PID=$!

# Если консьюмер умер — контейнер должен умереть тоже, иначе
# healthcheck зелёный, а события из Go никто не читает.
trap 'kill -TERM $CONSUMER_PID 2>/dev/null || true' TERM INT

# Встроенный сервер PHP. Для стенда достаточно; в проде здесь был бы
# php-fpm за nginx — встроенный однопоточный и держит один запрос за раз.
exec php -S 0.0.0.0:8000 -t /app/public
